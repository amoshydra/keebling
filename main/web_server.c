// The archive cap belongs with the asset table: the listing advertises it and
// the upload enforces it, and the two must not drift apart.
#define UI_ARCHIVE_MAX  (192 * 1024)   // the whole archive
#define UI_ENTRY_MAX    (96 * 1024)    // one file inside it
#define UI_ENTRY_COUNT  8              // more than the asset table has

typedef struct {
    const char *path;     // request URI
    const char *type;
    const char *file;     // name on the filesystem, and the upload whitelist
    const unsigned char *start;
    const unsigned char *end;
} static_asset_t;

// Static assets are public: they hold no secrets, and the page has to load
// before the user can supply the access code.
//
// This table is also the upload whitelist: only names that appear here can be
// written, so a request cannot invent a path. "/" and "/index.html" are the
// same file; the listing endpoint collapses them.
// Three files, because the UI is built into a bundle. The source files this
// table used to name no longer exist on the device; a request for one of them
// is a stale page, and a 404 is the honest answer.
static const static_asset_t s_assets[] = {
    { "/",              "text/html",              "index.html", index_html_start, index_html_end },
    { "/index.html",    "text/html",              "index.html", index_html_start, index_html_end },
    { "/style.css",     "text/css",               "style.css",  style_css_start,  style_css_end },
    { "/app.js",        "application/javascript", "app.js",     app_js_start,     app_js_end },
};
#define ASSET_COUNT (sizeof(s_assets) / sizeof(s_assets[0]))

static const static_asset_t *asset_by_file(const char *name) {
    for (size_t i = 0; i < ASSET_COUNT; i++) {
        if (strcmp(s_assets[i].file, name) == 0) return &s_assets[i];
    }
    return NULL;
}

// Which names the device will store and serve.
//
// A name is one or two segments of letters, digits, dot, dash and underscore.
// That set cannot spell "..", a drive letter or an absolute path, so an upload
// cannot walk out of the partition and a request cannot ask for one, whatever
// the archive claims. A segment may not start with a dot either, which rules
// out hidden files and the "." that would name a directory itself.
//
// It is deliberately NOT the asset table: the built-in UI is one build, and a
// user's own bundler may emit as many files, and directories, as it likes.
//
// Two names are reserved. "recover.html" repairs a broken upload, so it must
// come from the firmware and never from a request; the ".tmp" suffix belongs to
// the writer and must not be uploadable.
#define UI_NAME_MAX   128
#define UI_SEG_MAX    64
#define UI_DEPTH_MAX  2

static bool safe_segment(const char *seg, size_t n) {
    if (n == 0 || n >= UI_SEG_MAX) return false;
    if (seg[0] == '.') return false;

    for (size_t i = 0; i < n; i++) {
        const char c = seg[i];
        const bool ok = (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') ||
                        (c >= '0' && c <= '9') || c == '.' || c == '-' || c == '_';
        if (!ok) return false;
    }
    return true;
}

static bool safe_file_name(const char *name) {
    const size_t n = strlen(name);
    if (n == 0 || n >= UI_NAME_MAX) return false;

    int depth = 1;
    const char *seg = name;
    for (size_t i = 0; i <= n; i++) {
        if (i < n && name[i] != '/') continue;
        if (!safe_segment(seg, (size_t)(&name[i] - seg))) return false;
        if (i < n) {
            depth++;
            seg = &name[i] + 1;
        }
    }
    if (depth > UI_DEPTH_MAX) return false;

    const char *base = strrchr(name, '/');
    base = base ? base + 1 : name;
    if (strcmp(base, "recover.html") == 0) return false;
    const size_t bn = strlen(base);
    if (bn > 4 && strcmp(base + bn - 4, ".tmp") == 0) return false;

    return true;
}

// A bundler emits more than scripts: fonts, images, source maps. Guessing by
// extension is less wrong than calling everything octet-stream.
static const char *type_for_name(const char *name) {
    const char *dot = strrchr(name, '.');
    if (!dot) return "application/octet-stream";
    if (!strcmp(dot, ".html")) return "text/html";
    if (!strcmp(dot, ".css")) return "text/css";
    if (!strcmp(dot, ".js") || !strcmp(dot, ".mjs")) return "application/javascript";
    if (!strcmp(dot, ".json") || !strcmp(dot, ".map")) return "application/json";
    if (!strcmp(dot, ".svg")) return "image/svg+xml";
    if (!strcmp(dot, ".png")) return "image/png";
    if (!strcmp(dot, ".jpg") || !strcmp(dot, ".jpeg")) return "image/jpeg";
    if (!strcmp(dot, ".gif")) return "image/gif";
    if (!strcmp(dot, ".ico")) return "image/x-icon";
    if (!strcmp(dot, ".woff2")) return "font/woff2";
    if (!strcmp(dot, ".woff")) return "font/woff";
    if (!strcmp(dot, ".ttf")) return "font/ttf";
    if (!strcmp(dot, ".txt")) return "text/plain";
    return "application/octet-stream";
}

#define UI_LIST_MAX 32

typedef struct { char name[UI_NAME_MAX]; size_t size; } stored_entry_t;
typedef struct { stored_entry_t *items; size_t count; size_t cap; } stored_list_t;

static void collect_stored(const char *name, size_t size, void *ctx) {
    stored_list_t *l = ctx;
    if (l->count == l->cap) return;
    if (!safe_file_name(name)) return;   // never offer what would not be served
    if (strcmp(name, SCREEN_IMAGE_NAME) == 0) return;   // not a web file
    snprintf(l->items[l->count].name, UI_NAME_MAX, "%s", name);
    l->items[l->count].size = size;
    l->count++;
}


