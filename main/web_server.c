// Recent log output. Without this the device is a black box once TinyUSB owns
// the USB port, which makes field bugs like "the socket will not reconnect"
// impossible to diagnose.
static esp_err_t logs_handler(httpd_req_t *req) {
    if (!req_authorised(req)) {
        httpd_resp_send_err(req, HTTPD_403_FORBIDDEN, "forbidden");
        return ESP_FAIL;
    }
    static char buf[4096];
    log_buffer_read(buf, sizeof(buf));
    httpd_resp_set_type(req, "text/plain");
    return httpd_resp_sendstr(req, buf);
}

// What the host learns about us from the USB descriptors. Without this the
// report descriptor can only be inspected with a USB analyser or by digging
// through the browser's HID internals.
static esp_err_t hid_handler(httpd_req_t *req) {
    if (!req_authorised(req)) {
        httpd_resp_send_err(req, HTTPD_403_FORBIDDEN, "forbidden");
        return ESP_FAIL;
    }

    size_t len = 0;
    const uint8_t *desc = usb_hid_report_descriptor(&len);

    cJSON *root = cJSON_CreateObject();
    if (!root) {
        httpd_resp_send_err(req, HTTPD_500_INTERNAL_SERVER_ERROR, "oom");
        return ESP_FAIL;
    }

    cJSON_AddStringToObject(root, "product", usb_hid_product_name());
    cJSON_AddStringToObject(root, "manufacturer", usb_hid_string(1));
    cJSON_AddStringToObject(root, "serial", usb_hid_string(3));
    cJSON_AddStringToObject(root, "interface", usb_hid_string(4));
    cJSON_AddNumberToObject(root, "endpoint_size", usb_hid_endpoint_size());
    cJSON_AddNumberToObject(root, "poll_interval_ms", usb_hid_poll_interval_ms());
    cJSON_AddNumberToObject(root, "report_descriptor_len", (double)len);

    char *hex = malloc(len * 3 + 1);
    if (!hex) {
        cJSON_Delete(root);
        httpd_resp_send_err(req, HTTPD_500_INTERNAL_SERVER_ERROR, "oom");
        return ESP_FAIL;
    }
    size_t o = 0;
    for (size_t i = 0; i < len; i++) {
        o += snprintf(hex + o, len * 3 + 1 - o, i ? " %02X" : "%02X", desc[i]);
    }
    cJSON_AddStringToObject(root, "report_descriptor_hex", hex);
    free(hex);

    char *json = cJSON_PrintUnformatted(root);
    cJSON_Delete(root);
    if (!json) {
        httpd_resp_send_err(req, HTTPD_500_INTERNAL_SERVER_ERROR, "oom");
        return ESP_FAIL;
    }
    httpd_resp_set_type(req, "application/json");
    // Never cached: a stale answer here reads as "nothing happened", which is
    // the same trap the assets avoid.
    httpd_resp_set_hdr(req, "Cache-Control", "no-store");
    esp_err_t r = httpd_resp_sendstr(req, json);
    free(json);
    return r;
}

static esp_err_t scan_handler(httpd_req_t *req) {
    if (!req_authorised(req)) {
        httpd_resp_send_err(req, HTTPD_403_FORBIDDEN, "forbidden");
        return ESP_FAIL;
    }

    wifi_ap_record_t *recs = NULL;
    uint16_t n = 0;
    if (wifi_mgr_scan(&recs, &n) != ESP_OK) {
        httpd_resp_send_err(req, HTTPD_500_INTERNAL_SERVER_ERROR, "scan failed");
        return ESP_FAIL;
    }

    cJSON *root = cJSON_CreateObject();
    cJSON *arr = root ? cJSON_AddArrayToObject(root, "networks") : NULL;
    for (uint16_t i = 0; arr && i < n; i++) {
        cJSON *o = cJSON_CreateObject();
        if (!o) break;
        cJSON_AddStringToObject(o, "ssid", (const char *)recs[i].ssid);
        cJSON_AddNumberToObject(o, "rssi", recs[i].rssi);
        cJSON_AddBoolToObject(o, "secure", recs[i].authmode != WIFI_AUTH_OPEN);
        cJSON_AddItemToArray(arr, o);
    }
    free(recs);

    char *json = root ? cJSON_PrintUnformatted(root) : NULL;
    cJSON_Delete(root);
    if (!json) {
        httpd_resp_send_err(req, HTTPD_500_INTERNAL_SERVER_ERROR, "oom");
        return ESP_FAIL;
    }
    httpd_resp_set_type(req, "application/json");
    // Never cached: a stale answer here reads as "nothing happened", which is
    // the same trap the assets avoid.
    httpd_resp_set_hdr(req, "Cache-Control", "no-store");
    esp_err_t r = httpd_resp_sendstr(req, json);
    free(json);
    return r;
}

// Read the whole request body. Returns the length, or -1 on error/overflow.
static int read_body(httpd_req_t *req, char *buf, size_t buflen) {
    if (req->content_len == 0 || req->content_len >= buflen) return -1;
    size_t got = 0;
    while (got < req->content_len) {
        int r = httpd_req_recv(req, buf + got, req->content_len - got);
        if (r <= 0) {
            if (r == HTTPD_SOCK_ERR_TIMEOUT) continue;
            return -1;
        }
        got += r;
    }
    buf[got] = '\0';
    return (int)got;
}

static esp_err_t save_handler(httpd_req_t *req) {
    if (req->method != HTTP_POST) {
        httpd_resp_send_err(req, HTTPD_405_METHOD_NOT_ALLOWED, "POST only");
        return ESP_FAIL;
    }
    if (!req_authorised(req)) {
        httpd_resp_send_err(req, HTTPD_403_FORBIDDEN, "forbidden");
        return ESP_FAIL;
    }

    char body[256];
    if (read_body(req, body, sizeof(body)) < 0) {
        httpd_resp_send_err(req, HTTPD_400_BAD_REQUEST, "bad body");
        return ESP_FAIL;
    }

    cJSON *root = cJSON_Parse(body);
    const cJSON *jssid = root ? cJSON_GetObjectItem(root, "ssid") : NULL;
    const cJSON *jpass = root ? cJSON_GetObjectItem(root, "pass") : NULL;
    bool ok = cJSON_IsString(jssid) && jssid->valuestring[0] &&
              (!jpass || cJSON_IsString(jpass));
    char ssid[33] = {0}, pass[65] = {0};
    if (ok) {
        snprintf(ssid, sizeof(ssid), "%s", jssid->valuestring);
        snprintf(pass, sizeof(pass), "%s", jpass ? jpass->valuestring : "");
    }
    cJSON_Delete(root);

    if (!ok || wifi_mgr_set_creds(ssid, pass) != ESP_OK) {
        httpd_resp_send_err(req, HTTPD_400_BAD_REQUEST, "invalid ssid/password");
        return ESP_FAIL;
    }

    ESP_LOGW(TAG, "network credentials saved, restarting");
    input_release_all();
    httpd_resp_set_type(req, "text/plain");
    httpd_resp_sendstr(req, "saved, restarting");
    vTaskDelay(pdMS_TO_TICKS(400));   // let the response land
    esp_restart();
    return ESP_OK;   // not reached
}

static esp_err_t forget_handler(httpd_req_t *req) {
    if (req->method != HTTP_POST) {
        httpd_resp_send_err(req, HTTPD_405_METHOD_NOT_ALLOWED, "POST only");
        return ESP_FAIL;
    }
    if (!req_authorised(req)) {
        httpd_resp_send_err(req, HTTPD_403_FORBIDDEN, "forbidden");
        return ESP_FAIL;
    }

    wifi_mgr_forget();
    ESP_LOGW(TAG, "network credentials forgotten, restarting");
    input_release_all();
    httpd_resp_set_type(req, "text/plain");
    httpd_resp_sendstr(req, "forgotten, restarting");
    vTaskDelay(pdMS_TO_TICKS(400));
    esp_restart();
    return ESP_OK;   // not reached
}

// ---------------------------------------------------------------------------
// Device settings
//
// One JSON blob, stored verbatim. The firmware only reads the keys it acts on
// (currently usb_product / usb_manufacturer), so a UI-only setting never
// becomes a firmware change.
// ---------------------------------------------------------------------------

static esp_err_t settings_get_handler(httpd_req_t *req) {
    if (!req_authorised(req)) {
        httpd_resp_send_err(req, HTTPD_403_FORBIDDEN, "forbidden");
        return ESP_FAIL;
    }
    httpd_resp_set_type(req, "application/json");
    // Never cached, for the same reason as the assets: a stale read here reads
    // as "my change did not save".
    httpd_resp_set_hdr(req, "Cache-Control", "no-store");
    return httpd_resp_sendstr(req, settings_json());
}

static esp_err_t settings_post_handler(httpd_req_t *req) {
    if (req->method != HTTP_POST) {
        httpd_resp_send_err(req, HTTPD_405_METHOD_NOT_ALLOWED, "POST only");
        return ESP_FAIL;
    }
    if (!req_authorised(req)) {
        httpd_resp_send_err(req, HTTPD_403_FORBIDDEN, "forbidden");
        return ESP_FAIL;
    }

    static char body[SETTINGS_MAX];
    if (read_body(req, body, sizeof(body)) < 0) {
        httpd_resp_send_err(req, HTTPD_400_BAD_REQUEST, "bad body");
        return ESP_FAIL;
    }
    if (settings_set_json(body) != ESP_OK) {
        httpd_resp_send_err(req, HTTPD_400_BAD_REQUEST, "invalid settings");
        return ESP_FAIL;
    }
    // screen_text may have changed, and the text screen is drawn from it each
    // time - but nothing would redraw it until a tap or a wake.
    display_request_refresh();
    httpd_resp_set_type(req, "text/plain");
    return httpd_resp_sendstr(req, "ok");
}

// Settings that only apply at boot (the USB name in particular) need a restart
// to take effect, and the host has to re-read the descriptors after that.
static esp_err_t restart_handler(httpd_req_t *req) {
    if (req->method != HTTP_POST) {
        httpd_resp_send_err(req, HTTPD_405_METHOD_NOT_ALLOWED, "POST only");
        return ESP_FAIL;
    }
    if (!req_authorised(req)) {
        httpd_resp_send_err(req, HTTPD_403_FORBIDDEN, "forbidden");
        return ESP_FAIL;
    }
    ESP_LOGW(TAG, "restart requested");
    input_release_all();
    httpd_resp_set_type(req, "text/plain");
    httpd_resp_sendstr(req, "restarting");
    vTaskDelay(pdMS_TO_TICKS(400));
    esp_restart();
    return ESP_OK;   // not reached
}

