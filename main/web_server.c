// Protocol message types (must match main/web/pad.js and main/web/macro.js)
#define MSG_MOUSE     0x01
#define MSG_KEYBOARD  0x02
#define MSG_CONSUMER  0x03
#define MSG_PING      0x04
#define MSG_RELEASE   0x05

// Static buffer: the largest message is 8 bytes. Avoiding malloc on every
// mouse move keeps the heap stable at 100+ messages/second.
static uint8_t s_ws_buf[64];

static void handle_message(const uint8_t *b, size_t len) {
    switch (b[0]) {
    case MSG_MOUSE:
        if (len >= 5) input_mouse(b[3], (int8_t)b[1], (int8_t)b[2], (int8_t)b[4]);
        break;
    case MSG_KEYBOARD:
        if (len >= 8) {
            uint8_t keys[6] = { b[2], b[3], b[4], b[5], b[6], b[7] };
            input_keyboard(b[1], keys);
        }
        break;
    case MSG_CONSUMER:
        if (len >= 3) input_consumer((uint16_t)(b[1] | (b[2] << 8)));
        break;
    case MSG_PING:
        input_heartbeat();
        break;
    case MSG_RELEASE:
        input_release_all();
        break;
    default:
        ESP_LOGW(TAG, "Unknown WS message 0x%02X", b[0]);
        break;
    }
}

static esp_err_t ws_handler(httpd_req_t *req) {
    if (req->method == HTTP_GET) {
        // Handshake. The token arrives as a query parameter because the
        // browser WebSocket API cannot set an Authorization header.
        //
        // Note on ordering: esp_http_server sends the "101 Switching
        // Protocols" response BEFORE invoking this handler, so a rejected
        // client briefly sees an open socket. That is not a bypass --
        // httpd_sess_process() tears the session down when a handler returns
        // non-OK, so the data-frame path below is never reached for an
        // unauthenticated connection. Do not "simplify" this into a check
        // inside handle_message().
        if (!req_authorised(req)) {
            httpd_resp_send_err(req, HTTPD_403_FORBIDDEN, "forbidden");
            return ESP_FAIL;   // closes the session
        }
        ESP_LOGI(TAG, "WebSocket handshake accepted");
        display_status(LCD_LINE_WEBUI, "web ui active");
        return ESP_OK;
    }

    httpd_ws_frame_t pkt = { .type = HTTPD_WS_TYPE_BINARY };
    esp_err_t ret = httpd_ws_recv_frame(req, &pkt, 0);   // get length
    if (ret != ESP_OK) {
        ESP_LOGE(TAG, "ws_recv_frame(len) failed: %s", esp_err_to_name(ret));
        return ret;
    }
    if (pkt.len == 0) return ESP_OK;

    if (pkt.len > sizeof(s_ws_buf)) {
        ESP_LOGW(TAG, "Oversized WS frame (%u bytes), dropping session", (unsigned)pkt.len);
        return ESP_FAIL;
    }

    pkt.payload = s_ws_buf;
    ret = httpd_ws_recv_frame(req, &pkt, pkt.len);
    if (ret != ESP_OK) {
        ESP_LOGE(TAG, "ws_recv_frame(data) failed: %s", esp_err_to_name(ret));
        return ret;
    }

    handle_message(s_ws_buf, pkt.len);
    return ESP_OK;
}

// ---------------------------------------------------------------------------
// Start
// ---------------------------------------------------------------------------

esp_err_t web_server_start(void) {
    // Not ESP_ERROR_CHECK: a WiFi failure should leave the SoftAP-less device
    // able to report the problem, not abort into a boot loop.
    esp_err_t err = wifi_mgr_start();
    if (err != ESP_OK) {
        ESP_LOGE(TAG, "wifi_mgr_start: %s", esp_err_to_name(err));
        display_status(LCD_LINE_NET, "wifi FAILED");
        // fall through: the HTTP server can still come up
    }

    httpd_config_t cfg = HTTPD_DEFAULT_CONFIG();
    cfg.max_open_sockets = 7;
    cfg.lru_purge_enable = true;
    // The default is 8 and we register more than that; at 15 the 9th
    // registration returned ESP_ERR_HTTPD_HANDLERS_FULL and, through
    // ESP_ERROR_CHECK, became a boot loop. Sized with headroom now.
    cfg.max_uri_handlers = 24;

    if (httpd_start(&s_server, &cfg) != ESP_OK) {
        ESP_LOGE(TAG, "httpd_start failed");
        return ESP_FAIL;
    }

    // One entry per asset, all served by static_handler.
    static httpd_uri_t asset_uris[ASSET_COUNT];
    for (size_t i = 0; i < ASSET_COUNT; i++) {
        asset_uris[i].uri = s_assets[i].path;
        asset_uris[i].method = HTTP_GET;
        asset_uris[i].handler = static_handler;
        asset_uris[i].user_ctx = NULL;
        asset_uris[i].is_websocket = false;
        asset_uris[i].handle_ws_control_frames = false;
        asset_uris[i].supported_subprotocol = NULL;
    }

    httpd_uri_t uris[] = {
        { .uri = "/auth",       .method = HTTP_GET,  .handler = auth_handler },
        { .uri = "/ws",         .method = HTTP_GET,  .handler = ws_handler, .is_websocket = true },
        { .uri = "/bootloader", .method = HTTP_POST, .handler = bootloader_handler },
        { .uri = "/scan",       .method = HTTP_GET,  .handler = scan_handler },
        { .uri = "/logs",       .method = HTTP_GET,  .handler = logs_handler },
        { .uri = "/hid",        .method = HTTP_GET,  .handler = hid_handler },
        { .uri = "/save",       .method = HTTP_POST, .handler = save_handler },
        { .uri = "/forget",     .method = HTTP_POST, .handler = forget_handler },
        { .uri = "/settings",   .method = HTTP_GET,  .handler = settings_get_handler },
        { .uri = "/settings",   .method = HTTP_POST, .handler = settings_post_handler },
        { .uri = "/restart",    .method = HTTP_POST, .handler = restart_handler },
    };

    // Log rather than ESP_ERROR_CHECK: a full handler table should degrade to
    // "that endpoint 404s", not reboot the device.
    size_t registered = 0;
    for (size_t i = 0; i < ASSET_COUNT; i++) {
        esp_err_t err = httpd_register_uri_handler(s_server, &asset_uris[i]);
        if (err != ESP_OK) {
            ESP_LOGE(TAG, "register %s failed: %s", asset_uris[i].uri, esp_err_to_name(err));
        } else {
            registered++;
        }
    }
    for (size_t i = 0; i < sizeof(uris) / sizeof(uris[0]); i++) {
        esp_err_t err = httpd_register_uri_handler(s_server, &uris[i]);
        if (err != ESP_OK) {
            ESP_LOGE(TAG, "register %s failed: %s", uris[i].uri, esp_err_to_name(err));
        } else {
            registered++;
        }
    }

    ESP_LOGI(TAG, "HTTP server started on port %d (%zu handlers)",
             cfg.server_port, registered);
    return ESP_OK;
}

void web_server_stop(void) {
    if (s_server) {
        httpd_stop(s_server);
        s_server = NULL;
    }
}

int web_server_client_count(void) {
    return wifi_mgr_client_count();
}
