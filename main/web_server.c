// Streams the stored copy of `name`, or returns ESP_ERR_NOT_FOUND when there
// is nothing servable and the embedded copy should be used instead. Sending
// in chunks keeps a 16 KB macros.js off the stack.
static esp_err_t serve_stored(httpd_req_t *req, const char *name) {
    FILE *f = ui_fs_open(name);
    if (!f) return ESP_ERR_NOT_FOUND;

    char buf[512];
    size_t n;
    while ((n = fread(buf, 1, sizeof(buf), f)) > 0) {
        if (httpd_resp_send_chunk(req, buf, n) != ESP_OK) {
            fclose(f);
            return ESP_FAIL;   // headers are out; the embedded copy is no help
        }
    }
    bool truncated = ferror(f);
    fclose(f);
    if (truncated) return ESP_FAIL;

    return httpd_resp_send_chunk(req, NULL, 0);
}

// req->uri carries the query string, so "/?token=..." has to match the asset
// path "/". Comparing the whole string meant every asset link with a query -
// including the URL printed on the LCD - fell through to a 404, and the token
// shortcut never worked: the gate was the only way in.
static bool uri_matches(const char *uri, const char *path) {
    const size_t n = strlen(path);
    return strncmp(uri, path, n) == 0 && (uri[n] == '\0' || uri[n] == '?');
}

// Always the compiled-in copy, never the filesystem. This page exists to repair
// a broken uploaded UI, so it must not itself be replaceable by an upload - which
// is why it is not in s_assets and has no entry in the upload whitelist.
static esp_err_t recover_handler(httpd_req_t *req) {
    httpd_resp_set_type(req, "text/html");
    httpd_resp_set_hdr(req, "Cache-Control", "no-store");
    return httpd_resp_send(req, (const char *)recover_html_start,
                           recover_html_end - recover_html_start);
}

static esp_err_t static_handler(httpd_req_t *req) {
    for (size_t i = 0; i < ASSET_COUNT; i++) {
        if (!uri_matches(req->uri, s_assets[i].path)) continue;

        httpd_resp_set_type(req, s_assets[i].type);

        // Never let a browser cache these. The whole point of the filesystem is
        // that a file can be replaced without a flash, and a cached copy would
        // make an upload look like it did nothing - the most confusing way this
        // feature could fail. They are small and the device is on the same LAN.
        httpd_resp_set_hdr(req, "Cache-Control", "no-store");

        // An uploaded file wins over the built-in one. An empty file counts as
        // absent (ui_fs_open), so a zero-length upload cannot shadow a working
        // page - the embedded copy is always the floor.
        if (serve_stored(req, s_assets[i].file) == ESP_OK) return ESP_OK;

        return httpd_resp_send(req, (const char *)s_assets[i].start,
                               s_assets[i].end - s_assets[i].start);
    }
    // Not one of the built-in paths: any stored file, by its own flat name.
    // The same rule the upload applied is applied here, so a request for
    // "../nvs" or "/etc/passwd" is a 404 rather than a path.
    const char *path = req->uri[0] == '/' ? req->uri + 1 : req->uri;
    const size_t len = strcspn(path, "?");
    if (len > 0 && len < UI_NAME_MAX) {
        char name[UI_NAME_MAX];
        memcpy(name, path, len);
        name[len] = '\0';

        if (safe_file_name(name)) {
            httpd_resp_set_type(req, type_for_name(name));
            httpd_resp_set_hdr(req, "Cache-Control", "no-store");
            if (serve_stored(req, name) == ESP_OK) return ESP_OK;
        }
    }

    httpd_resp_send_err(req, HTTPD_404_NOT_FOUND, "not found");
    return ESP_FAIL;
}

// ---------------------------------------------------------------------------
// UI files on the device
//
// The front end can be updated over WiFi instead of by flashing: uploads land
// on the LittleFS partition and are served in preference to the embedded
// copies. Deleting one brings the built-in copy back, so the worst an upload
// can do is need a reset - never a reflash.
// ---------------------------------------------------------------------------

// What the upload page needs to show: every file, whether the device is
// serving a stored copy, and how much room is left.
static esp_err_t ui_files_handler(httpd_req_t *req) {
    if (!req_authorised(req)) {
        httpd_resp_send_err(req, HTTPD_403_FORBIDDEN, "forbidden");
        return ESP_FAIL;
    }

    cJSON *root = cJSON_CreateObject();
    cJSON *arr = root ? cJSON_AddArrayToObject(root, "files") : NULL;
    if (!root || !arr) {
        cJSON_Delete(root);
        httpd_resp_send_err(req, HTTPD_500_INTERNAL_SERVER_ERROR, "oom");
        return ESP_FAIL;
    }

    cJSON_AddBoolToObject(root, "mounted", ui_fs_mounted());
    cJSON_AddNumberToObject(root, "max_size", UI_ARCHIVE_MAX);

    size_t total = 0, used = 0;
    if (ui_fs_usage(&total, &used) == ESP_OK) {
        cJSON_AddNumberToObject(root, "total", (double)total);
        cJSON_AddNumberToObject(root, "used", (double)used);
    }

    // The partition's files first, then the built-in ones that are not stored.
    // The listing follows the filesystem rather than the asset table, because a
    // user's own build may contain files this firmware has never heard of.
    static stored_entry_t stored[UI_LIST_MAX];
    stored_list_t list = { stored, 0, UI_LIST_MAX };
    ui_fs_list(collect_stored, &list);

    for (size_t i = 0; i < list.count; i++) {
        const static_asset_t *asset = asset_by_file(stored[i].name);
        cJSON *o = cJSON_CreateObject();
        if (!o) continue;
        cJSON_AddStringToObject(o, "name", stored[i].name);
        // A zero-length file is never served, so it is not "stored" either.
        cJSON_AddBoolToObject(o, "stored", stored[i].size > 0);
        cJSON_AddNumberToObject(o, "size", (double)stored[i].size);
        cJSON_AddNumberToObject(o, "embedded",
                                asset ? (double)(asset->end - asset->start) : 0);
        cJSON_AddItemToArray(arr, o);
    }

    for (size_t i = 0; i < ASSET_COUNT; i++) {
        bool listed = false;
        for (size_t j = 0; j < i && !listed; j++) {
            listed = strcmp(s_assets[j].file, s_assets[i].file) == 0;
        }
        if (listed) continue;   // "/" and "/index.html" are one file

        bool already = false;
        for (size_t j = 0; j < list.count && !already; j++) {
            already = strcmp(stored[j].name, s_assets[i].file) == 0;
        }
        if (already) continue;

        cJSON *o = cJSON_CreateObject();
        if (!o) continue;
        cJSON_AddStringToObject(o, "name", s_assets[i].file);
        cJSON_AddBoolToObject(o, "stored", false);
        cJSON_AddNumberToObject(o, "size", 0);
        cJSON_AddNumberToObject(o, "embedded",
                                (double)(s_assets[i].end - s_assets[i].start));
        cJSON_AddItemToArray(arr, o);
    }

    char *json = cJSON_PrintUnformatted(root);
    cJSON_Delete(root);
    if (!json) {
        httpd_resp_send_err(req, HTTPD_500_INTERNAL_SERVER_ERROR, "oom");
        return ESP_FAIL;
    }
    httpd_resp_set_type(req, "application/json");
    // Never cached: a stale answer here reads as "nothing happened", which is
    // the same trap the assets avoid.
    httpd_resp_set_hdr(req, "Cache-Control", "no-store");
    esp_err_t r = httpd_resp_sendstr(req, json);
    free(json);
    return r;
}

// Read and discard up to `limit` bytes of the request body. Only used before
// refusing an upload: a client that is still sending can then read the error
// response instead of seeing the connection drop mid-transfer. Best effort,
// and the caller closes the connection afterwards.
static void drain_body(httpd_req_t *req, size_t limit) {
    char buf[512];
    size_t left = req->content_len < limit ? req->content_len : limit;
    while (left > 0) {
        int r = httpd_req_recv(req, buf, left < sizeof(buf) ? left : sizeof(buf));
        if (r <= 0) break;   // includes a timeout: answer now
        left -= r;
    }
}

// The UI is built as a bundle by tools/build-web.mjs - index.html, style.css
// and app.js - and shipped as one archive. Uploading the archive rather than a
// file at a time is what keeps the shell and the script it loads from ever
// being one version apart, which is the failure that leaves a blank page with
// no way back except a reflash.
//
// The archive is stored, not deflated: the bundle is already minified, so the
// archive's job is to make a whole UI arrive as one object. Requiring no
// inflate keeps this to a header parser.
//
// Every entry is written to "<name>.tmp" and renamed only after the whole
// archive has arrived, so an interrupted upload leaves the previous UI serving.
// Names are matched against the asset table, never used to build a path.
// ---------------------------------------------------------------------------

#define ZIP_LOCAL_SIG    0x04034b50u
#define ZIP_CENTRAL_SIG  0x02014b50u
#define ZIP_END_SIG      0x06054b50u

static uint16_t le16(const uint8_t *p) { return (uint16_t)(p[0] | (p[1] << 8)); }
static uint32_t le32(const uint8_t *p) {
    return (uint32_t)p[0] | ((uint32_t)p[1] << 8) | ((uint32_t)p[2] << 16) | ((uint32_t)p[3] << 24);
}

typedef struct {
    char name[UI_NAME_MAX];   // validated by safe_file_name() on arrival
    FILE *f;
} zip_entry_t;

// Exactly n bytes, or -1. A slow phone is not a failure; one that vanished is.
static int recv_exact(httpd_req_t *req, uint8_t *buf, size_t n) {
    size_t got = 0;
    int stalls = 0;
    while (got < n) {
        int r = httpd_req_recv(req, (char *)buf + got, n - got);
        if (r == HTTPD_SOCK_ERR_TIMEOUT) {
            if (++stalls > 6) return -1;
            continue;
        }
        if (r <= 0) return -1;
        stalls = 0;
        got += (size_t)r;
    }
    return 0;
}

static esp_err_t upload_refuse(httpd_req_t *req, const char *status, int code, const char *why) {
    drain_body(req, UI_ARCHIVE_MAX);
    httpd_resp_set_status(req, status);
    httpd_resp_set_type(req, "text/plain");
    httpd_resp_send(req, why, HTTPD_RESP_USE_STRLEN);
    return ESP_FAIL;
}

// POST /ui/upload with a stored zip as the body.
static esp_err_t ui_upload_handler(httpd_req_t *req) {
    if (req->method != HTTP_POST) {
        httpd_resp_send_err(req, HTTPD_405_METHOD_NOT_ALLOWED, "POST only");
        return ESP_FAIL;
    }
    if (!req_authorised(req)) {
        httpd_resp_send_err(req, HTTPD_403_FORBIDDEN, "forbidden");
        return ESP_FAIL;
    }
    if (!ui_fs_mounted()) {
        return upload_refuse(req, "503 Service Unavailable", 503, "no filesystem");
    }
    if (req->content_len == 0) {
        return upload_refuse(req, "400 Bad Request", 400, "empty body");
    }
    if (req->content_len > UI_ARCHIVE_MAX) {
        ESP_LOGW(TAG, "archive of %u bytes over the %u byte cap",
                 (unsigned)req->content_len, (unsigned)UI_ARCHIVE_MAX);
        return upload_refuse(req, "413 Content Too Large", 413, "archive too large");
    }

    zip_entry_t entries[UI_ENTRY_COUNT];
    size_t count = 0;
    const char *why = "not a stored zip";
    int code = 400;
    bool complete = false;      // false means: publish nothing, whatever got here
    uint8_t hdr[30];

    for (;;) {
        if (recv_exact(req, hdr, 4) != 0) { why = "body ended early"; break; }

        const uint32_t sig = le32(hdr);
        // The central directory is the natural end of the entries. It is not
        // parsed: the local headers already carried everything needed.
        if (sig == ZIP_CENTRAL_SIG || sig == ZIP_END_SIG) { complete = true; break; }
        if (sig != ZIP_LOCAL_SIG) break;
        if (recv_exact(req, hdr + 4, 26) != 0) { why = "body ended early"; break; }

        if (le16(hdr + 8) != 0) { why = "archive must be stored, not deflated"; break; }

        const uint32_t size = le32(hdr + 18);
        const uint16_t name_len = le16(hdr + 26);
        const uint16_t extra_len = le16(hdr + 28);

        if (size == 0) { why = "empty entry"; break; }
        if (size > UI_ENTRY_MAX) { why = "entry too large"; break; }
        if (name_len == 0 || name_len >= UI_NAME_MAX) { why = "bad entry name"; break; }

        char name[UI_NAME_MAX];
        if (recv_exact(req, (uint8_t *)name, name_len) != 0) { why = "body ended early"; break; }
        name[name_len] = '\0';

        uint8_t skip[64];
        for (uint16_t left = extra_len; left > 0; ) {
            const size_t take = left < sizeof(skip) ? left : sizeof(skip);
            if (recv_exact(req, skip, take) != 0) { why = "body ended early"; break; }
            left = (uint16_t)(left - take);
        }

        if (!safe_file_name(name)) {
            ESP_LOGW(TAG, "archive entry '%s' refused: not a flat file name", name);
            why = "bad file name";
            break;
        }
        if (count == UI_ENTRY_COUNT) { why = "too many files"; break; }

        bool dup = false;
        for (size_t i = 0; i < count; i++) dup = dup || strcmp(entries[i].name, name) == 0;
        if (dup) { why = "duplicate entry"; break; }

        FILE *f = ui_fs_open_temp(name);
        if (!f) { why = "cannot write"; code = 500; break; }

        uint32_t left = size;
        bool wrote = true;
        while (left > 0) {
            uint8_t buf[512];
            const size_t take = left < sizeof(buf) ? left : sizeof(buf);
            if (recv_exact(req, buf, take) != 0) { why = "upload interrupted"; code = 408; wrote = false; break; }
            if (fwrite(buf, 1, take, f) != take) { why = "cannot write"; code = 500; wrote = false; break; }
            left -= (uint32_t)take;
        }
        if (!wrote) { ui_fs_discard(name, f); break; }

        snprintf(entries[count].name, sizeof(entries[count].name), "%s", name);
        entries[count].f = f;
        count++;
    }

    // The shell is not optional: a UI without index.html has nothing to load,
    // and the sweep below would delete the one that did. Checked here as well
    // as in the page, because an archive can arrive from curl.
    if (complete && count > 0) {
        bool has_shell = false;
        for (size_t i = 0; i < count && !has_shell; i++) {
            has_shell = strcmp(entries[i].name, "index.html") == 0;
        }
        if (!has_shell) {
            complete = false;
            why = "archive has no index.html";
        }
    }

    // Published only when the archive ended where it said it would. A transfer
    // that dies halfway leaves temps, never a UI: the previous one keeps
    // serving, and the next upload replaces them.
    if (!complete || count == 0) {
        for (size_t i = 0; i < count; i++) ui_fs_discard(entries[i].name, entries[i].f);
        if (count == 0 && complete) why = "archive carried no files";
        return upload_refuse(req, code == 400 ? "400 Bad Request" : "408 Request Timeout",
                             code, why);
    }

    // Past this point the archive is complete. The rename is the moment the new
    // UI goes live.
    for (size_t i = 0; i < count; i++) {
        if (ui_fs_commit(entries[i].name, entries[i].f) != ESP_OK) {
            for (size_t j = i + 1; j < count; j++) ui_fs_discard(entries[j].name, entries[j].f);
            return upload_refuse(req, "500 Internal Server Error", 500, "cannot store");
        }
    }

    // The archive is the whole UI, so anything it did not carry is from an
    // older build and only takes room. The screen image shares this partition
    // and is not a web file: it stays.
    const char *keep[UI_ENTRY_COUNT + 1];
    for (size_t i = 0; i < count; i++) keep[i] = entries[i].name;
    keep[count] = SCREEN_IMAGE_NAME;
    ui_fs_prune(keep, count + 1);

    drain_body(req, UI_ARCHIVE_MAX);   // the central directory, so the answer lands
    display_request_refresh();
    ESP_LOGI(TAG, "%u files stored from one archive", (unsigned)count);

    char msg[64];
    snprintf(msg, sizeof(msg), "%u files stored", (unsigned)count);
    httpd_resp_set_type(req, "text/plain");
    return httpd_resp_sendstr(req, msg);
}

// POST /ui/reset?name=<whitelisted> deletes one stored file; ?all=1 deletes
// every one. Either way the embedded copy is served again. Reset-all exists so
// a broken view script is recoverable from another view's page; a broken
// index.html takes the whole shell with it and is not recoverable this way.
static esp_err_t ui_reset_handler(httpd_req_t *req) {
    if (req->method != HTTP_POST) {
        httpd_resp_send_err(req, HTTPD_405_METHOD_NOT_ALLOWED, "POST only");
        return ESP_FAIL;
    }
    if (!req_authorised(req)) {
        httpd_resp_send_err(req, HTTPD_403_FORBIDDEN, "forbidden");
        return ESP_FAIL;
    }

    char query[160];
    if (httpd_req_get_url_query_str(req, query, sizeof(query)) != ESP_OK) {
        httpd_resp_send_err(req, HTTPD_400_BAD_REQUEST, "name or all required");
        return ESP_FAIL;
    }

    char all[4];
    if (httpd_query_key_value(query, "all", all, sizeof(all)) == ESP_OK) {
        // Everything except the screen image, which is not a web file.
        static stored_entry_t stored[UI_LIST_MAX];
        stored_list_t list = { stored, 0, UI_LIST_MAX };
        ui_fs_list(collect_stored, &list);
        for (size_t i = 0; i < list.count; i++) {
            if (strcmp(stored[i].name, SCREEN_IMAGE_NAME) == 0) continue;
            if (ui_fs_remove(stored[i].name) != ESP_OK) {
                httpd_resp_send_err(req, HTTPD_500_INTERNAL_SERVER_ERROR, "cannot remove");
                return ESP_FAIL;
            }
        }
        ESP_LOGI(TAG, "all uploaded UI files removed");
        httpd_resp_set_type(req, "text/plain");
        return httpd_resp_sendstr(req, "reset");
    }

    char name[UI_NAME_MAX];
    if (httpd_query_key_value(query, "name", name, sizeof(name)) != ESP_OK ||
        !safe_file_name(name)) {
        httpd_resp_send_err(req, HTTPD_400_BAD_REQUEST, "unknown file");
        return ESP_FAIL;
    }
    if (ui_fs_remove(name) != ESP_OK) {
        httpd_resp_send_err(req, HTTPD_500_INTERNAL_SERVER_ERROR, "cannot remove");
        return ESP_FAIL;
    }

    display_request_refresh();
    ESP_LOGI(TAG, "%s: stored copy removed, embedded copy is back", name);
    httpd_resp_set_type(req, "text/plain");
    return httpd_resp_sendstr(req, "reset");
}

// ---------------------------------------------------------------------------
// Custom screen image
//
// Not a UI asset: the device holds exactly one file under a fixed name, so it
// gets its own route rather than an entry in the asset table - which is the
// upload whitelist for *web files*, and this is not one. The name is a
// constant in screen_image.h, never anything from the request.
// ---------------------------------------------------------------------------

// GET /screen/image streams the stored file, so the settings page can show what
// the device actually holds rather than trusting its own conversion. The body
// includes the header, so the page can check the format and the CRC itself.
// 404 when there is nothing valid, which is also the answer the BOOT cycle's
// skip rule is built on.
static esp_err_t screen_image_get_handler(httpd_req_t *req) {
    if (!req_authorised(req)) {
        httpd_resp_send_err(req, HTTPD_403_FORBIDDEN, "forbidden");
        return ESP_FAIL;
    }

    FILE *f = ui_fs_open(SCREEN_IMAGE_NAME);
    if (!f || !screen_image_check(f)) {
        if (f) fclose(f);
        httpd_resp_send_err(req, HTTPD_404_NOT_FOUND, "no image");
        return ESP_FAIL;
    }

    httpd_resp_set_type(req, "application/octet-stream");
    // Never cached: a stale image here reads as "my upload did nothing".
    httpd_resp_set_hdr(req, "Cache-Control", "no-store");

    rewind(f);   // the check left the stream on the payload
    char buf[512];
    size_t n;
    while ((n = fread(buf, 1, sizeof(buf), f)) > 0) {
        if (httpd_resp_send_chunk(req, buf, n) != ESP_OK) {
            fclose(f);
            return ESP_FAIL;
        }
    }
    bool truncated = ferror(f);
    fclose(f);
    if (truncated) return ESP_FAIL;

    return httpd_resp_send_chunk(req, NULL, 0);
}

// POST /screen/image with the packed file as the body. Streamed to the
// filesystem while the header and CRC are checked on the fly, and only renamed
// into place once the whole thing validates - so a body the device would not
// draw never replaces an image it would.
static esp_err_t screen_image_upload_handler(httpd_req_t *req) {
    if (req->method != HTTP_POST) {
        httpd_resp_send_err(req, HTTPD_405_METHOD_NOT_ALLOWED, "POST only");
        return ESP_FAIL;
    }
    if (!req_authorised(req)) {
        httpd_resp_send_err(req, HTTPD_403_FORBIDDEN, "forbidden");
        return ESP_FAIL;
    }

    // Either format's exact size is acceptable; anything else is a different
    // format and there is nothing to salvage from it. Which of the two a body
    // claims to be is settled by its own format byte as it streams - a 0x02
    // header cannot satisfy the length and size checks in a 6,408-byte body,
    // so the disagreement is refused rather than guessed at.
    if (req->content_len != SCREEN_IMAGE_FILE_GREY4 &&
        req->content_len != SCREEN_IMAGE_FILE_RGB565) {
        ESP_LOGW(TAG, "screen image: %u bytes, expected %u or %u",
                 (unsigned)req->content_len,
                 (unsigned)SCREEN_IMAGE_FILE_GREY4,
                 (unsigned)SCREEN_IMAGE_FILE_RGB565);
        drain_body(req, SCREEN_IMAGE_FILE_RGB565);
        httpd_resp_set_status(req, "400 Bad Request");
        httpd_resp_set_type(req, "text/plain");
        httpd_resp_send(req, "expected 6408 or 25608 bytes", HTTPD_RESP_USE_STRLEN);
        return ESP_FAIL;
    }

    if (!ui_fs_mounted()) {
        // Drained for the same reason as the over-size case: the client should
        // see this answer, not a dropped socket.
        drain_body(req, SCREEN_IMAGE_FILE_RGB565);
        httpd_resp_set_status(req, "503 Service Unavailable");
        httpd_resp_set_type(req, "text/plain");
        httpd_resp_send(req, "no filesystem", HTTPD_RESP_USE_STRLEN);
        return ESP_FAIL;
    }

    FILE *f = ui_fs_open_temp(SCREEN_IMAGE_NAME);
    if (!f) {
        httpd_resp_send_err(req, HTTPD_500_INTERNAL_SERVER_ERROR, "cannot write");
        return ESP_FAIL;
    }

    screen_image_upload_t check;
    screen_image_upload_begin(&check);

    char buf[512];
    size_t left = req->content_len;
    int stalls = 0;
    while (left > 0) {
        int r = httpd_req_recv(req, buf, left < sizeof(buf) ? left : sizeof(buf));
        if (r == HTTPD_SOCK_ERR_TIMEOUT) {
            if (++stalls > 6) break;
            continue;
        }
        if (r <= 0) break;
        stalls = 0;
        if (fwrite(buf, 1, r, f) != (size_t)r) break;
        screen_image_upload_feed(&check, (const uint8_t *)buf, (size_t)r);
        left -= r;
    }

    if (left != 0) {
        ui_fs_discard(SCREEN_IMAGE_NAME, f);
        ESP_LOGW(TAG, "screen image: upload interrupted, %u bytes missing",
                 (unsigned)left);
        httpd_resp_send_err(req, HTTPD_408_REQ_TIMEOUT, "upload interrupted");
        return ESP_FAIL;
    }
    if (!screen_image_upload_ok(&check)) {
        ui_fs_discard(SCREEN_IMAGE_NAME, f);
        ESP_LOGW(TAG, "screen image refused: header or CRC check failed");
        httpd_resp_send_err(req, HTTPD_400_BAD_REQUEST, "invalid image");
        return ESP_FAIL;
    }

    if (ui_fs_commit(SCREEN_IMAGE_NAME, f) != ESP_OK) {
        httpd_resp_send_err(req, HTTPD_500_INTERNAL_SERVER_ERROR, "cannot store");
        return ESP_FAIL;
    }

    // Redraw now if the image screen is the mode currently on display; otherwise
    // the new picture would sit in the filesystem until the next tap or wake.
    display_request_refresh();
    ESP_LOGI(TAG, "screen image stored (%s, %u bytes)",
             check.format == SCREEN_IMAGE_FORMAT_RGB565 ? "RGB565" : "grey4",
             (unsigned)(SCREEN_IMAGE_HEADER + check.expect_payload));
    httpd_resp_set_type(req, "text/plain");
    return httpd_resp_sendstr(req, "stored");
}

// POST /screen/reset deletes the stored image, so the BOOT cycle stops offering
// the mode and the settings page goes back to "nothing stored".
static esp_err_t screen_image_reset_handler(httpd_req_t *req) {
    if (req->method != HTTP_POST) {
        httpd_resp_send_err(req, HTTPD_405_METHOD_NOT_ALLOWED, "POST only");
        return ESP_FAIL;
    }
    if (!req_authorised(req)) {
        httpd_resp_send_err(req, HTTPD_403_FORBIDDEN, "forbidden");
        return ESP_FAIL;
    }

    if (ui_fs_remove(SCREEN_IMAGE_NAME) != ESP_OK) {
        httpd_resp_send_err(req, HTTPD_500_INTERNAL_SERVER_ERROR, "cannot remove");
        return ESP_FAIL;
    }

    display_request_refresh();     // the image is gone; drop to the next mode
    ESP_LOGI(TAG, "screen image removed");
    httpd_resp_set_type(req, "text/plain");
    return httpd_resp_sendstr(req, "reset");
}

// Lets the web UI check a code before opening the WebSocket, so a wrong code
// gives a clear message instead of a silently failing connection.
static esp_err_t auth_handler(httpd_req_t *req) {
    if (req->method != HTTP_GET) {
        httpd_resp_send_err(req, HTTPD_405_METHOD_NOT_ALLOWED, "GET only");
        return ESP_FAIL;
    }
    if (!req_authorised(req)) {
        httpd_resp_send_err(req, HTTPD_403_FORBIDDEN, "forbidden");
        return ESP_FAIL;
    }
    httpd_resp_set_status(req, "204 No Content");
    return httpd_resp_send(req, NULL, 0);
}

// Reboot into the chip's ROM download mode.
//
// The flag lives in an RTC register, so it survives a reset but not a power
// cycle - unplugging is always a safe escape.
//
// Two things about this are counter-intuitive and were established the hard way:
//
//  1. esp_restart() must NOT be used. esp_restart_noos() configures RTC WDT
//     stage0 as RESET_SYSTEM with a 1 s timeout and calls
//     wdt_hal_set_flashboot_en(true). flashboot_mod_en exists precisely to keep
//     the watchdog running even when software disables it, and nothing feeds it
//     in download mode, so the chip enters download mode and is reset back into
//     the app about a second later. Measured: 303a:1001 for ~1 s, then 303a:4004.
//     RTC_CNTL_SW_SYS_RST avoids that because it does not arm the watchdog.
//
//  2. The mode reached is the ROM's USB-OTG *DFU* path (PID 303a:0009, with an
//     interface of class 0xFE/0x01/0x01), NOT the USB-Serial-JTAG download mode
//     (303a:1001) that esptool speaks. Flashing from here needs dfu-util via
//     `idf.py dfu` + `idf.py dfu-flash`, not `idf.py flash`.
static void reboot_to_bootloader(void) {
    REG_WRITE(RTC_CNTL_OPTION1_REG, RTC_CNTL_FORCE_DOWNLOAD_BOOT);
    REG_WRITE(RTC_CNTL_OPTIONS0_REG, RTC_CNTL_SW_SYS_RST);
    for (;;) { }   // not reached
}

static esp_err_t bootloader_handler(httpd_req_t *req) {
    if (req->method != HTTP_POST) {
        httpd_resp_send_err(req, HTTPD_405_METHOD_NOT_ALLOWED, "POST only");
        return ESP_FAIL;
    }
    if (!req_authorised(req)) {
        httpd_resp_send_err(req, HTTPD_403_FORBIDDEN, "forbidden");
        return ESP_FAIL;
    }

    ESP_LOGW(TAG, "Reboot to ROM download mode requested");
    input_release_all();

    httpd_resp_set_type(req, "text/plain");
    httpd_resp_send(req, "rebooting to download mode", HTTPD_RESP_USE_STRLEN);

    // Let the response actually reach the client before we disappear.
    vTaskDelay(pdMS_TO_TICKS(400));

    reboot_to_bootloader();
    return ESP_OK;   // not reached
}

