static const char *TAG = "web_server";

// The SoftAP password is the device code, so there is exactly one secret.
// Never put any part of the code in the SSID: beacons are public.

// Embedded web files (generated by EMBED_FILES in main/CMakeLists.txt)
extern const unsigned char index_html_start[] asm("_binary_index_html_start");
extern const unsigned char index_html_end[]   asm("_binary_index_html_end");
extern const unsigned char app_js_start[]     asm("_binary_app_js_start");
extern const unsigned char app_js_end[]       asm("_binary_app_js_end");

static httpd_handle_t s_server = NULL;
static esp_netif_t *s_ap_netif = NULL;
static int s_clients = 0;

// ---------------------------------------------------------------------------
// Request guards
//
// The web UI can type arbitrary keystrokes into the host, so it is treated as
// a privileged console. Three independent checks:
//
//   1. Host allowlist  - defeats DNS rebinding (attacker resolves evil.com to
//                        our LAN IP; the Host header still says evil.com).
//   2. Origin allowlist - defeats cross-site WebSocket hijacking (any page you
//                        visit can open ws:// to a LAN address from JS).
//   3. Token            - defeats anyone else already on the network.
// ---------------------------------------------------------------------------

// Is this hostname one of ours? Compares the host part only, port stripped.
static bool host_is_ours(const char *host) {
    if (!host || !*host) return false;

    char h[80];
    size_t n = 0;
    for (const char *p = host; *p && *p != ':' && *p != '/' && n < sizeof(h) - 1; p++) {
        h[n++] = (char)tolower((unsigned char)*p);
    }
    h[n] = '\0';
    if (n == 0) return false;

    if (strcmp(h, AP_MDNS_NAME ".local") == 0) return true;

    // Whatever IP we currently hold on the AP interface (192.168.4.1 normally,
    // but never hardcode it).
    if (s_ap_netif) {
        esp_netif_ip_info_t ip;
        if (esp_netif_get_ip_info(s_ap_netif, &ip) == ESP_OK) {
            char buf[16];
            snprintf(buf, sizeof(buf), IPSTR, IP2STR(&ip.ip));
            if (strcmp(h, buf) == 0) return true;
        }
    }
    return false;
}

static bool req_host_allowed(httpd_req_t *req) {
    char host[96];
    if (httpd_req_get_hdr_value_str(req, "Host", host, sizeof(host)) != ESP_OK) {
        return false;   // HTTP/1.1 requires Host
    }
    if (!host_is_ours(host)) {
        ESP_LOGW(TAG, "rejected Host: %s", host);
        return false;
    }
    return true;
}

// Origin, when present, must point at one of our own hostnames. Browsers
// always send it on WebSocket upgrades, so a failure here means the request
// came from a page we did not serve.
static bool req_origin_allowed(httpd_req_t *req) {
    char origin[128];
    if (httpd_req_get_hdr_value_str(req, "Origin", origin, sizeof(origin)) != ESP_OK) {
        // Non-browser client (curl, test scripts). Host + token still apply.
        return true;
    }
    const char *p = origin;
    if (strncmp(p, "http://", 7) == 0)       p += 7;
    else if (strncmp(p, "https://", 8) == 0) p += 8;
    else {
        ESP_LOGW(TAG, "rejected Origin: %s", origin);   // e.g. "null"
        return false;
    }
    if (!host_is_ours(p)) {
        ESP_LOGW(TAG, "rejected Origin: %s", origin);
        return false;
    }
    return true;
}

// Token from ?token=...  (the browser WebSocket API cannot set headers).
static bool req_token_ok(httpd_req_t *req) {
    char query[160];
    char token[64];

    if (httpd_req_get_url_query_str(req, query, sizeof(query)) != ESP_OK) return false;
    if (httpd_query_key_value(query, "token", token, sizeof(token)) != ESP_OK) return false;

    return security_check_token(token);
}

// Best-effort source address, used only to throttle brute force. Returns 0
// when the address is unavailable, which disables throttling for that request
// rather than failing it.
static uint32_t peer_ip(httpd_req_t *req) {
    int fd = httpd_req_to_sockfd(req);
    if (fd < 0) return 0;

    struct sockaddr_storage ss;
    socklen_t sl = sizeof(ss);
    if (getpeername(fd, (struct sockaddr *)&ss, &sl) != 0) return 0;

    if (ss.ss_family == AF_INET) {
        return (uint32_t)((struct sockaddr_in *)&ss)->sin_addr.s_addr;
    }
#if LWIP_IPV6
    if (ss.ss_family == AF_INET6) {
        const uint8_t *b = ((struct sockaddr_in6 *)&ss)->sin6_addr.s6_addr;
        uint32_t h = 2166136261u;                       // FNV-1a
        for (int i = 0; i < 16; i++) { h ^= b[i]; h *= 16777619u; }
        return h ? h : 1;                               // 0 means "unknown"
    }
#endif
    return 0;
}

// Full gate for privileged endpoints.
static bool req_authorised(httpd_req_t *req) {
    uint32_t ip = peer_ip(req);

    if (!req_host_allowed(req))   return false;
    if (!req_origin_allowed(req)) return false;

    if (security_ip_locked(ip)) {
        ESP_LOGW(TAG, "auth attempt from a throttled source");
        return false;
    }
    if (!req_token_ok(req)) {
        security_note_ip_result(ip, false);
        return false;
    }
    security_note_ip_result(ip, true);
    return true;
}

