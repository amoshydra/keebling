// Protocol message types (must match main/web/pad.js and main/web/macro.js)
#define MSG_MOUSE     0x01
#define MSG_KEYBOARD  0x02
#define MSG_CONSUMER  0x03
#define MSG_PING      0x04
#define MSG_RELEASE   0x05

// Static buffer: the largest message is 8 bytes. Avoiding malloc on every
// mouse move keeps the heap stable at 100+ messages/second.
static uint8_t s_ws_buf[64];

static void handle_message(const uint8_t *b, size_t len) {
    switch (b[0]) {
    case MSG_MOUSE:
        if (len >= 5) input_mouse(b[3], (int8_t)b[1], (int8_t)b[2], (int8_t)b[4]);
        break;
    case MSG_KEYBOARD:
        if (len >= 8) {
            uint8_t keys[6] = { b[2], b[3], b[4], b[5], b[6], b[7] };
            input_keyboard(b[1], keys);
        }
        break;
    case MSG_CONSUMER:
        if (len >= 3) input_consumer((uint16_t)(b[1] | (b[2] << 8)));
        break;
    case MSG_PING:
        input_heartbeat();
        break;
    case MSG_RELEASE:
        input_release_all();
        break;
    default:
        ESP_LOGW(TAG, "Unknown WS message 0x%02X", b[0]);
        break;
    }
}

static esp_err_t ws_handler(httpd_req_t *req) {
    if (req->method == HTTP_GET) {
        // Handshake. The token arrives as a query parameter because the
        // browser WebSocket API cannot set an Authorization header.
        //
        // Note on ordering: esp_http_server sends the "101 Switching
        // Protocols" response BEFORE invoking this handler, so a rejected
        // client briefly sees an open socket. That is not a bypass --
        // httpd_sess_process() tears the session down when a handler returns
        // non-OK, so the data-frame path below is never reached for an
        // unauthenticated connection. Do not "simplify" this into a check
        // inside handle_message().
        if (!req_authorised(req)) {
            httpd_resp_send_err(req, HTTPD_403_FORBIDDEN, "forbidden");
            return ESP_FAIL;   // closes the session
        }
        ESP_LOGI(TAG, "WebSocket handshake accepted");
        display_status(LCD_LINE_WEBUI, "web ui active");
        return ESP_OK;
    }

    httpd_ws_frame_t pkt = { .type = HTTPD_WS_TYPE_BINARY };
    esp_err_t ret = httpd_ws_recv_frame(req, &pkt, 0);   // get length
    if (ret != ESP_OK) {
        ESP_LOGE(TAG, "ws_recv_frame(len) failed: %s", esp_err_to_name(ret));
        return ret;
    }
    if (pkt.len == 0) return ESP_OK;

    if (pkt.len > sizeof(s_ws_buf)) {
        ESP_LOGW(TAG, "Oversized WS frame (%u bytes), dropping session", (unsigned)pkt.len);
        return ESP_FAIL;
    }

    pkt.payload = s_ws_buf;
    ret = httpd_ws_recv_frame(req, &pkt, pkt.len);
    if (ret != ESP_OK) {
        ESP_LOGE(TAG, "ws_recv_frame(data) failed: %s", esp_err_to_name(ret));
        return ret;
    }

    handle_message(s_ws_buf, pkt.len);
    return ESP_OK;
}

